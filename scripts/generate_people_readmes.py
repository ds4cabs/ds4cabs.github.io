#!/usr/bin/env python3
"""Generate role directory README files from assets/data/people.json."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
REGISTRY = ROOT / "assets" / "data" / "people.json"
BASE_URL = "https://ds4cabs.github.io"


def md_link(label: str, url: str | None) -> str:
    return f"[{label}]({url})" if url else "—"


def github_link(url: str | None) -> str:
    if not url:
        return "—"
    handle = url.rstrip("/").rsplit("/", 1)[-1]
    return md_link(f"@{handle}", url)


def profile_link(profile: str | None) -> str:
    return md_link("View", f"{BASE_URL}/{profile}") if profile else "—"


def source_link() -> str:
    return "[`assets/data/people.json`](../assets/data/people.json)"


def table(headers: list[str], rows: list[list[str]], align_right: set[int] | None = None) -> str:
    align_right = align_right or set()
    separators = ["---:" if i in align_right else "---" for i in range(len(headers))]
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join(separators) + "|"]
    lines.extend("| " + " | ".join(row) + " |" for row in rows)
    return "\n".join(lines)


def directory_readme(title: str, description: str, rows: list[list[str]]) -> str:
    return f"""# {title}

{description}

{table(['Person', 'Role', 'Affiliation', 'GitHub', 'LinkedIn', 'Profile'], rows)}

> Generated from [`assets/data/people.json`](../assets/data/people.json). Run `python3 scripts/generate_people_readmes.py` after editing the registry.

## Local preview

From the repository root:

```bash
python3 -m http.server 8000
```
"""


def generate(people: list[dict]) -> dict[Path, str]:
    mentors = [p for p in people if p.get("active", True) and p.get("type") in {"mentor", "admin"}]
    administrators = [p for p in people if p.get("active", True) and p.get("type") in {"leader", "admin"}]
    mentees = sorted(
        [p for p in people if p.get("type") == "mentee"],
        key=lambda p: -int(p["year"]),
    )

    def role_rows(entries: list[dict]) -> list[list[str]]:
        return [
            [
                p["name"],
                p.get("role") or p["type"].title(),
                p.get("affiliation") or "—",
                github_link(p.get("github")),
                md_link("Profile", p.get("linkedin")),
                profile_link(p.get("profile")),
            ]
            for p in entries
        ]

    mentee_rows = [
        [
            p["name"],
            str(p["year"]),
            p.get("major") or "—",
            p.get("affiliation") or "—",
            github_link(p.get("github")),
            md_link("Profile", p.get("linkedin")),
            profile_link(p.get("profile")),
            source_link(),
        ]
        for p in mentees
    ]

    profile_entries = [p for p in people if p.get("profile")]
    legacy_rows = [
        [
            p["name"],
            p["type"].title(),
            profile_link(p["profile"]),
            f"[`../{p['profile']}`](../{p['profile']})",
        ]
        for p in profile_entries
    ]

    return {
        ROOT / "mentor" / "README.md": directory_readme(
            "DS4CABS Mentor Profiles",
            "Evergreen DS4CABS mentor and admin directory.",
            role_rows(mentors),
        ),
        ROOT / "admin" / "README.md": directory_readme(
            "DS4CABS Admin and Program Leadership",
            "Evergreen DS4CABS program leadership and administrator directory.",
            role_rows(administrators),
        ),
        ROOT / "mentee" / "README.md": f"""# DS4CABS Mentee Profiles

Mentee and intern records grouped automatically by program year.

{table(['Person', 'Program year', 'Major / field', 'Affiliation', 'GitHub', 'LinkedIn', 'Profile', 'Source'], mentee_rows, {1})}

> An em dash (—) indicates unavailable information. This table is generated from [`assets/data/people.json`](../assets/data/people.json).

## Local preview

From the repository root:

```bash
python3 -m http.server 8000
```

Then open `http://localhost:8000/mentee/<profile-file>.html`.
""",
        ROOT / "people" / "README.md": f"""# Legacy People Profile URLs

Profile records now live in the central [`assets/data/people.json`](../assets/data/people.json) registry. The HTML files in this directory are compatibility redirects for previously shared links.

{table(['Person', 'Role', 'Current URL', 'Current source'], legacy_rows)}

> Generated by `python3 scripts/generate_people_readmes.py`.
""",
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = parser.parse_args()

    people = json.loads(REGISTRY.read_text(encoding="utf-8"))
    outputs = generate(people)
    stale: list[str] = []
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(content, encoding="utf-8")

    if stale:
        print("Stale generated files: " + ", ".join(stale))
        return 1
    if not args.check:
        print(f"Generated {len(outputs)} README files from {len(people)} registry entries.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
